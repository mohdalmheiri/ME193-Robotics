"""
Real vs simulated fixed-speed drift test, side by side (rubric: "simulation and reality
somewhat close").

Inputs:
  --real <csv> [<csv> ...]   runs from robot/calibration/drift_test.py (each has a .json next
                             to it with the hand measurements and the leg set-up)
  docs/data/hand_tests_sim_heading.csv   from robot/sim_hand_tests.py (nominal robot + 20
                             lopsided ones, same test in simulation; rerun it first with the
                             measured rpm: --rpm <value>)
How it works: for each real run it picks the simulated test with the same leg set-up (in /
out of step) and draws heading over time: the real robot (red, from its motion sensor),
the simulated nominal robot (black) and the 20 lopsided ones (light blue). Below, a table:
the real hand measurements next to the simulated nominal value and the lopsided median and
range. A real result inside the lopsided range means the simulator's left/right
randomization covers this robot.
Output: docs/media/drift_real_vs_sim_<in|out>.png and docs/drift_real_vs_sim.md
Run from the HW8 folder:  ../../.venv/bin/python robot/compare_drift.py --real robot/runs/<...>.csv
"""

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HW8 = Path(__file__).resolve().parent.parent
SIM = HW8 / "docs" / "data" / "hand_tests_sim_heading.csv"
TEST = {"in": "in step", "out": "out of step"}

ap = argparse.ArgumentParser()
ap.add_argument("--real", nargs="+", required=True, help="drift_test CSV file(s)")
ap.add_argument("--sim", default=str(SIM), help="sim heading CSV (e.g. docs/data/hand_tests_sim_heading_spec_100.csv)")
a = ap.parse_args()
SIM = Path(a.sim)

sim = defaultdict(lambda: defaultdict(list))          # test -> robot -> rows
for row in csv.DictReader(open(SIM)):
    sim[row["test"]][row["robot"]].append(
        (float(row["t"]), float(row["heading_deg"]), float(row["sideways_mm"]), float(row["forward_mm"])))

lines = ["# Drift test: real robot vs simulator", "",
         "Real: `robot/calibration/drift_test.py` (heading from the motion sensor; distance, sideways "
         "and turn measured by hand). Simulator: `robot/sim_hand_tests.py`, nominal robot and 20 "
         "lopsided robots. Generated by `robot/compare_drift.py`.", "",
         "| Run | Measure | Real | Sim nominal | Sim lopsided: median (range) | Real inside the lopsided range? |",
         "|---|---|---|---|---|---|"]
for path in a.real:
    path = Path(path)
    summ = json.loads(path.with_suffix(".json").read_text())
    test = TEST[summ["legs"]]
    real = np.array([[float(r["t"]), float(r["heading_deg"])] for r in csv.DictReader(open(path))])
    fig, ax = plt.subplots(figsize=(8, 5))
    finals = defaultdict(list)
    for name, rows in sim[test].items():
        arr = np.array(rows)
        nominal = name == "nominal"
        ax.plot(arr[:, 0], arr[:, 1], color="black" if nominal else "tab:blue",
                lw=2 if nominal else 0.8, alpha=1 if nominal else 0.4,
                label="simulator, nominal robot" if nominal else None)
        side, fwd = arr[-1, 2], arr[-1, 3]
        vals = {"distance_mm": math.hypot(side, fwd), "sideways_mm": side, "turn_deg": arr[-1, 1]}
        for k, v in vals.items():
            finals["nominal" if nominal else "lopsided"].append((k, v))
    ax.plot([], [], color="tab:blue", alpha=0.4, label="simulator, 20 lopsided robots")
    ax.plot(real[:, 0], real[:, 1] - real[0, 1], color="tab:red", lw=2.5, label="real robot (motion sensor)")
    ax.set(xlabel="time (s)", ylabel="heading change (deg, + = turned left)",
           title=f"Fixed-speed drift test, legs {test}, {summ['percent']} %")
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    out = HW8 / "docs" / "media" / f"drift_real_vs_sim_{summ['legs']}.png"
    fig.savefig(out, dpi=110)
    print(f"Saved {out.relative_to(HW8)}")
    for k, label in (("distance_mm", "distance (mm)"), ("sideways_mm", "sideways (mm, + = right)"),
                     ("turn_deg", "turn (deg, + = left)")):
        nom = [v for kk, v in finals["nominal"] if kk == k][0]
        lop = np.array([v for kk, v in finals["lopsided"] if kk == k])
        real_v = summ.get(k, float("nan"))
        inside = "-" if math.isnan(real_v) else ("yes" if lop.min() <= real_v <= lop.max() else "NO")
        lines.append(f"| {path.stem} | {label} | {real_v:.0f} | {nom:.0f} | {np.median(lop):.0f} "
                     f"({lop.min():.0f} to {lop.max():.0f}) | {inside} |")
    lines.append(f"| {path.stem} | turn from motion sensor (deg) | {summ['imu_turn_deg']:.0f} | | | |")
(HW8 / "docs" / "drift_real_vs_sim.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
